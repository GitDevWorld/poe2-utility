// 괄호 속 숨은 효과는 아이템에 문구로 나오지 않는다 (경매장 매물에도 stat이 없음)
const text = (m) => m[3].replace(/ \(숨은 효과.*\)$/, "").replace(/–/g, "-");
for (const m of mods) {
  const re = new RegExp(m[4].replace("^", "(^|· )"), "i");
  const clash = mods.filter((o) => o !== m && re.test(text(o)) && (m[2] == null || o[2] == null || o[2] === m[2]));
  const sameText = clash.filter((o) => o[4] === m[4]);
  if (clash.length > sameText.length) console.warn(`패턴 겹침 ${m[1]}:${m[0]} /${m[4]}/ →`, clash.map((o) => o[3]));
}

